const jose = require('jose');

const API_KEY = process.env.NEXT_PUBLIC_FIREBASE_API_KEY || 'AIzaSyDIsHh1RJ7ztj_groWSw0FYjWlfGRYkT2c';
const PROJECT_ID = process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || 'meeshop-de48e';
const GOOGLE_JWKS_URL = 'https://www.googleapis.com/service_accounts/v1/jwk/securetoken@system.gserviceaccount.com';

let total = 0;
let passed = 0;

function assert(condition, title, detail) {
  total++;
  if (condition) {
    passed++;
    console.log(`✅ ${title}: PASSED`);
  } else {
    console.error(`❌ ${title}: FAILED - ${detail || ''}`);
    process.exitCode = 1;
  }
}

async function runLiveAuthTests() {
  console.log('========================================================================');
  console.log(`SORAYVA — LIVE FIREBASE AUTH VALIDATION (PROJECT: ${PROJECT_ID})`);
  console.log('========================================================================\n');

  const testEmail = `patron.live.${Date.now()}@example.com`;
  const testPassword = 'Password@Live2026!';

  // --- TEST 1: LIVE USER REGISTRATION ---
  console.log('--- 1. Testing Live Customer Registration ---');
  const signUpRes = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signUp?key=${API_KEY}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      email: testEmail,
      password: testPassword,
      returnSecureToken: true
    })
  });
  const signUpData = await signUpRes.json();
  assert(signUpRes.ok, 'Test 1.1: Live account created successfully in Firebase', JSON.stringify(signUpData));
  assert(Boolean(signUpData.localId), 'Test 1.2: Customer UID generated by Firebase Auth', signUpData.localId);
  assert(signUpData.email === testEmail, 'Test 1.3: Registered email matches input');
  assert(Boolean(signUpData.idToken), 'Test 1.4: Real Firebase ID Token received');

  const liveUid = signUpData.localId;
  const liveToken = signUpData.idToken;

  // --- TEST 2: CLOUDFLARE EDGE TOKEN VERIFICATION VIA GOOGLE JWKS ---
  console.log('\n--- 2. Testing Edge Server ID-Token Verification ---');
  try {
    const JWKS = jose.createRemoteJWKSet(new URL(GOOGLE_JWKS_URL));
    const expectedIssuer = `https://securetoken.google.com/${PROJECT_ID}`;

    const { payload } = await jose.jwtVerify(liveToken, JWKS, {
      issuer: expectedIssuer,
      audience: PROJECT_ID,
      algorithms: ['RS256']
    });

    assert(payload.sub === liveUid, 'Test 2.1: Token subject matches registered customer UID');
    assert(payload.email === testEmail, 'Test 2.2: Token email matches registered customer email');
    assert(payload.aud === PROJECT_ID, 'Test 2.3: Token audience matches project meeshop-de48e');
    assert(payload.iss === expectedIssuer, 'Test 2.4: Token issuer matches securetoken.google.com/meeshop-de48e');
  } catch (err) {
    assert(false, 'Test 2.1: Token verification via Google JWKS', err.message);
  }

  // --- TEST 3: DUPLICATE REGISTRATION REJECTION ---
  console.log('\n--- 3. Testing Duplicate Registration Rejection ---');
  const dupRes = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signUp?key=${API_KEY}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      email: testEmail,
      password: testPassword,
      returnSecureToken: true
    })
  });
  const dupData = await dupRes.json();
  assert(!dupRes.ok && dupData.error?.message === 'EMAIL_EXISTS', 'Test 3.1: Duplicate email registration correctly rejected with EMAIL_EXISTS');

  // --- TEST 4: CUSTOMER SIGN IN WITH VALID CREDENTIALS ---
  console.log('\n--- 4. Testing Sign In with Valid Credentials ---');
  const signInRes = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=${API_KEY}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      email: testEmail,
      password: testPassword,
      returnSecureToken: true
    })
  });
  const signInData = await signInRes.json();
  assert(signInRes.ok, 'Test 4.1: Customer signed in successfully with valid credentials');
  assert(signInData.localId === liveUid, 'Test 4.2: Signed in user UID matches registered user UID');

  // --- TEST 5: CUSTOMER SIGN IN WITH INCORRECT PASSWORD ---
  console.log('\n--- 5. Testing Sign In with Incorrect Password ---');
  const badSignRes = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=${API_KEY}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      email: testEmail,
      password: 'IncorrectPassword999!',
      returnSecureToken: true
    })
  });
  const badSignData = await badSignRes.json();
  assert(!badSignRes.ok && (badSignData.error?.message === 'INVALID_PASSWORD' || badSignData.error?.message === 'INVALID_LOGIN_CREDENTIALS'), 'Test 5.1: Incorrect password correctly rejected');

  // --- TEST 6: PASSWORD RESET DISPATCH ---
  console.log('\n--- 6. Testing Password Reset Request ---');
  const resetRes = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:sendOobCode?key=${API_KEY}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      requestType: 'PASSWORD_RESET',
      email: testEmail
    })
  });
  const resetData = await resetRes.json();
  assert(resetRes.ok && resetData.email === testEmail, 'Test 6.1: Password reset email dispatched by Firebase Auth');

  console.log('\n========================================================================');
  console.log(`LIVE AUTH VALIDATION: ${passed}/${total} TESTS PASSED`);
  console.log('========================================================================\n');

  if (passed !== total) {
    process.exit(1);
  } else {
    process.exit(0);
  }
}

runLiveAuthTests().catch(err => {
  console.error('Fatal test error:', err);
  process.exit(1);
});
